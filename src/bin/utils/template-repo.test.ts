import { templateRepoHttps, templateRepoSlug, templateRepoSsh } from "./template-repo";

describe("template repo", () => {
	it("points at the public template", () => {
		expect(templateRepoSlug).toBe("signaloid/Signaloid-Demo-API-AutogeneratedTemplate");
	});

	it("derives both clone URLs from the same slug", () => {
		expect(templateRepoSsh).toBe(`git@github.com:${templateRepoSlug}.git`);
		expect(templateRepoHttps).toBe(`${templateRepoSlug}.git`);
	});
});
