import * as fs from "fs";
import * as path from "path";
import inquirer from "inquirer";
import chalk from "chalk";
import { execa } from "execa";
import { templateRepoSlug, templateRepoSsh } from "./template-repo";

// Defines the structure for the login result
export interface LoginResult {
	success: boolean;
	token?: string;
}
const REPO_URL_SSH = templateRepoSsh;

let cachedToken: string | undefined = undefined;
/**
 * Logs the user into the GitHub npm registry and configures Git credentials for the project.
 * This method is non-interactive, robust, and suitable for CLI and CI/CD environments.
 *
 * @param outPath The directory where the .netrc and .npmrc files will be created.
 * @returns A promise that resolves with an object containing the success status and the token.
 */
export async function loginAndGetToken(outPath: string = process.cwd()): Promise<LoginResult> {
	if (!cachedToken && !(await promptForToken())) {
		return { success: false, token: undefined };
	}
	return writeAuthFiles(outPath);
}

/**
 * Whether a token has already been collected in this run.
 */
export function hasCachedToken(): boolean {
	return cachedToken !== undefined;
}

/**
 * Asks for a GitHub token and caches it for the rest of the run. Writes
 * nothing to disk.
 *
 * @returns The token, or undefined when the user cancelled.
 */
async function promptForToken(): Promise<string | undefined> {
	if (!cachedToken) {
		console.log(
			chalk.blue(
				"To clone the private repository and install packages, you need a GitHub Personal Access Token.",
			),
		);
		console.log(chalk.blue("Please create one at https://github.com/settings/tokens with the following scopes:"));
		console.log(chalk.yellow("- read:packages (for npm)"));
		console.log(chalk.yellow("- repo (for git clone)"));
		let token: string;
		try {
			const answers = await inquirer.prompt([
				{
					type: "password",
					name: "token",
					message: "Enter your GitHub Personal Access Token:",
					mask: "*",
					validate: (input: string) => {
						if (!input) {
							return "Token cannot be empty.";
						}
						// ghp_ is a classic PAT, gho_/ghu_/ghs_/ghr_ are OAuth and app
						// tokens, github_pat_ is fine-grained. GitHub does not promise a
						// fixed length for any of them, so only check the prefix.
						const githubTokenRegex = /^(gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{36,})$/;
						if (!githubTokenRegex.test(input)) {
							return "Invalid GitHub token format. Please check your token and try again.";
						}
						return true;
					},
				},
			]);
			token = answers.token;
		} catch (e: any) {
			if (e?.name === "ExitPromptError") {
				console.log("\nCancelled.");
				return undefined;
			}
			throw e;
		}
		cachedToken = token;
	}
	return cachedToken;
}

/**
 * Writes the cached token to a project-level .netrc and .npmrc.
 *
 * @param outPath The directory where the .netrc and .npmrc files will be created.
 */
async function writeAuthFiles(outPath: string): Promise<LoginResult> {
	try {
		// --- .netrc configuration for Git (project-level) ---
		const netrcPath = path.join(outPath, ".netrc");
		const netrcMachine = "github.com";
		const newNetrcEntry = `machine ${netrcMachine}\n  login x-access-token\n  password ${cachedToken}`;

		// For a project-level .netrc, we can just overwrite it.
		await fs.promises.writeFile(netrcPath, newNetrcEntry, { mode: 0o600 });
		console.log(chalk.green(`Successfully configured project-level .netrc for Git authentication!`));

		// --- .npmrc configuration for npm ---
		const npmrcPath = path.join(outPath, ".npmrc");
		const registryUrl = "https://npm.pkg.github.com/";
		const scope = "@signaloid";
		const authTokenLine = `//npm.pkg.github.com/:_authToken=${cachedToken}`;
		const registryLine = `${scope}:registry=${registryUrl}`;
		const headerComment = `# This file was generated by the Signaloid CLI to authenticate with GitHub`;

		let npmrcLines: string[] = [];
		if (fs.existsSync(npmrcPath)) {
			const content = await fs.promises.readFile(npmrcPath, "utf8");
			npmrcLines = content.split("\n").filter((line) => {
				const isAuthLine = line.includes("//npm.pkg.github.com/:_authToken=");
				const isRegistryLine = line.includes(":registry=https://npm.pkg.github.com");
				return (
					!isAuthLine && !isRegistryLine && !line.startsWith("# This file was generated by the Signaloid CLI")
				);
			});
		}

		const newNpmrcContent = [headerComment, ...npmrcLines, registryLine, authTokenLine].join("\n");
		await fs.promises.writeFile(npmrcPath, newNpmrcContent);
		console.log(chalk.green("Successfully configured .npmrc for GitHub Packages!"));

		return { success: true, token: cachedToken };
	} catch (error: any) {
		console.error(chalk.red("Failed to write authentication files:"), error.message);
		return { success: false, token: cachedToken };
	}
}

/**
 * A package the generated project depends on, used to probe registry access.
 */
const REGISTRY_PROBE_PACKAGE = "@signaloid/scce-sdk";

/**
 * Whether npm can read the @signaloid scope with the configuration already on
 * this machine.
 */
async function canReadSignaloidRegistry(): Promise<boolean> {
	try {
		await execa("npm", ["view", REGISTRY_PROBE_PACKAGE, "version"], { stdio: "ignore" });
		return true;
	} catch {
		return false;
	}
}

/**
 * Whether the repository can be listed with the given token over HTTPS.
 */
async function canReadTemplateRepoWithToken(token: string): Promise<boolean> {
	const httpsRepoUrl = `https://x-access-token:${token}@github.com/${templateRepoSlug}.git`;
	try {
		await execa("git", ["ls-remote", httpsRepoUrl], { stdio: "ignore" });
		return true;
	} catch {
		return false;
	}
}

/**
 * Checks that the template repository can be cloned and that npm can read the
 * @signaloid registry. Access to the repository says nothing about access to
 * the registry, so both are checked. Any token collected here is cached for
 * the rest of the run and written to the project later, so nothing is left
 * behind in the working directory.
 *
 * @returns A promise that resolves to true if both checks pass, and false otherwise.
 */
export async function checkGithubAuth(): Promise<boolean> {
	console.log(chalk.blue("Checking GitHub authentication..."));

	let hasRepoAccess = false;
	try {
		// Listing the remote refs is a cheap read check that avoids a full clone.
		await execa("git", ["ls-remote", REPO_URL_SSH], { stdio: "ignore" });
		console.log(chalk.green("GitHub SSH authentication successful."));
		hasRepoAccess = true;
	} catch (error) {
		console.log(chalk.yellow("GitHub SSH authentication failed. Let's try with a Personal Access Token."));
	}

	if (!hasRepoAccess) {
		const token = await promptForToken();
		if (!token) {
			console.error(chalk.red("GitHub login failed. Please check your token and permissions."));
			return false;
		}
		if (!(await canReadTemplateRepoWithToken(token))) {
			console.error(chalk.red(`Could not read ${templateRepoSlug} with the provided token.`));
			console.error(
				chalk.red(
					"The token may be invalid or missing the 'repo' scope, or your account may not have access to that repository.",
				),
			);
			return false;
		}
		console.log(chalk.green("GitHub token can read the template repository."));
	}

	// Repository access does not imply registry access. Catch a missing
	// read:packages scope now rather than minutes into "npm install".
	if (await canReadSignaloidRegistry()) {
		console.log(chalk.green("npm can read the @signaloid package registry."));
		return true;
	}

	console.log(chalk.yellow("npm cannot read the @signaloid package registry with your current npm configuration."));
	console.log(chalk.yellow("The project's dependencies will not install without a token."));

	const token = await promptForToken();
	if (!token) {
		console.error(
			chalk.red("A GitHub token with the 'read:packages' scope is required to install the dependencies."),
		);
		return false;
	}
	return true;
}
